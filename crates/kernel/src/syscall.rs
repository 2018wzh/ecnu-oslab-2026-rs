//! 系统调用分发 —— 用户程序进入内核的**唯一**入口 (U-mode 只能执行
//! `ecall` 陷入 S-mode)。因此它是唯一必须把用户当敌意的地方: a7 调用号、
//! 每个参数、缓冲区地址都可能是任意 64 位数。
//!
//! 本模块三条规则: 从 trapframe 读参数 (陷入后寄存器只在 trapframe 里);
//! 返回前把结果写回 trapframe 的 `a0` (ABI 返回通道); 推进返回地址
//! (在 trap 层做, 见 [`dispatch`] 的说明)。
//!
//! 未实现的调用必须返回负错误码 (NoSys/-38), 而不是假装成功 —— 一个
//! 假的 0 会让用户程序误以为操作成功, 问题在几十行后以无关现象出现。

use oslab_hal::arch::TrapFrame;
use oslab_uapi::{encode_ret, SysError, SysResult, Syscall, SYS_MAX};

use crate::mm::uvm::{copy_from_user, copy_to_user, copy_str_from_user};

// ===========================================================================
// 分发
// ===========================================================================

/// 分发一次系统调用, 返回 ABI 上的 `isize` (同时已写回 `tf.a0`)。
///
/// 返回地址推进在 trap.rs 的 `SyscallFromUser` 分支 (调用本函数之前,
/// 经 `advance_return_address_for_syscall`) 完成: 只发生在这条路径上,
/// 不存在"某个分支忘了推进"。且 `sepc` 是 RISC-V 名字, kernel 不该出现
/// CSR 名, 语义化接口换架构时调用点不用改。若不在 trap 层推进, 返回后
/// CPU 会重执行同一条 ecall —— 表现为 write 刷屏 / exit 退不掉 / 而
/// getpid 看起来正常 (掩盖了同一原因)。
///
/// 先用 `raw >= SYS_MAX` 粗筛 (挡掉垃圾大值), 再交给 `from_raw` 精确
/// 解码 (`match` 穷尽枚举保证"新增调用号忘了处理"编译失败)。两步都返回
/// `BadArg`, 都不 panic: 用户传非法调用号不能关掉整个系统。
///
/// 返回值既写 `a0` (ABI 给用户程序读) 又返回 `isize` (给 trap 内部用),
/// 两者来自同一值。

/// 单次 `write` 允许的最大长度。
///
/// `write` 逐字节读用户内存, 若用户传 `usize::MAX` 会把内核困在循环里
/// (拒绝服务)。显式设上限, "用户可控循环上界"是经典漏洞来源。4 KiB
/// 对典型输出绰绰有余。
const MAX_USER_WRITE: usize = 4096;

/// 提前返回一个错误码 (绕过 `SysResult` 的类型约束)。
///
/// `dispatch` 主体是 `let ret: SysResult = match ...`, 分支里需要中途
/// 返回时用这个显式编码函数。
fn return_err(e: SysError) -> SysResult {
    Err(e)
}

/// 分发一次系统调用, 返回**已编码**的 `isize` (负数 = 错误)。
pub fn dispatch(tf: &mut TrapFrame) -> isize { unimplemented!() }

